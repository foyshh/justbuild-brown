def photos(slug):
    """Split a project's photos into wide (landscape/square) and tall."""
    folder = os.path.join(IMG_ROOT, slug)
    wide, tall = [], []
    for f in sorted(os.listdir(folder)):
        if not f.lower().endswith('.jpg'):
            continue
        w, h = Image.open(os.path.join(folder, f)).size
        (tall if h > w * 1.05 else wide).append(f)
    return wide, tall


def src(slug, f):
    return f'../images/projects/{slug}/{f}'


